#!/usr/bin/env python3
"""Run all exhaustive solvers, cross-check them, and regenerate public data."""
import argparse
import datetime
import hashlib
import json
import os
import pathlib
import platform
import subprocess
import sys
import time

from nqueens import rows

ROOT = pathlib.Path(__file__).resolve().parents[1]


def run_json(build, name):
    executable = build / name
    if sys.platform == "win32":
        direct = build / (name + ".exe")
        executable = direct if direct.exists() else build / "Release" / direct.name
    started = time.perf_counter()
    output = subprocess.check_output([str(executable), "analyze"], text=True)
    elapsed = time.perf_counter() - started
    result = json.loads(output)
    result["runtime_seconds"] = round(elapsed, 6)
    return result


def save(path, data):
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")


def environment(threads):
    cpu = platform.processor() or "unknown"
    if pathlib.Path("/proc/cpuinfo").exists():
        for line in pathlib.Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                cpu = line.split(":", 1)[1].strip()
                break
    compiler = subprocess.check_output(["c++", "--version"], text=True).splitlines()[0]
    cmake = subprocess.check_output(["cmake", "--version"], text=True).splitlines()[0]
    return {"os": platform.platform(), "cpu": cpu, "logical_cpus": os.cpu_count(),
            "worker_threads": threads, "compiler": compiler, "cmake": cmake,
            "python": platform.python_version(), "build_type": "Release"}


def markdown(nqueens, ttt, puzzle, lights):
    lines = ["| N | Solutions | Recursive (s) | Iterative (s) |",
             "|---:|---:|---:|---:|"]
    for row in nqueens:
        lines.append(f"| {row['n']} | {row['solutions']:,} | {row['recursive_seconds']:.9f} | {row['iterative_seconds']:.9f} |")
    ntable = "\n".join(lines)
    overview = "\n".join([
        "| Project | Exhaustive result | Verification |",
        "|:--|:--|:--|",
        f"| N-Queens | N=18: **{nqueens[-1]['solutions']:,}** solutions | Two independent bitboard traversals; N=1–18 |",
        f"| Tic-Tac-Toe | **{ttt['reachable_positions']:,}** positions; **{ttt['complete_games']:,}** games | Game tree vs. state graph |",
        f"| 8-Puzzle | **{puzzle['reachable_states']:,}** states; diameter **{puzzle['diameter']}** | Replay every optimal path |",
        f"| Lights Out 5×5 | **{lights['solvable_states']:,}** solvable of **{lights['total_states']:,}** boards; max minimum **{lights['maximum_minimum_moves']}** | Gray enumeration vs. GF(2) for every board |",
    ])
    detail = ["# Generated result tables", "", "Generated by `scripts/generate_results.py` from executed binaries.",
              "Runtime is elapsed wall time and varies by machine and load.", "", "## N-Queens", "", ntable,
              "", "## Tic-Tac-Toe", "", "| Measure | Value |", "|:--|--:|"]
    for key in ("reachable_positions", "terminal_positions", "complete_games", "x_wins",
                "o_wins", "draws", "maximum_depth", "canonical_positions",
                "canonical_terminal_positions"):
        detail.append(f"| {key.replace('_', ' ')} | {ttt[key]:,} |")
    detail += ["", "## 8-Puzzle distance histogram", "", "| Optimal moves | States |",
               "|---:|---:|"]
    detail += [f"| {distance} | {count:,} |" for distance, count in enumerate(puzzle["histogram"])]
    detail += ["", "## Lights Out minimum-move histogram", "", "| Minimum presses | Boards |",
               "|---:|---:|"]
    detail += [f"| {moves} | {count:,} |" for moves, count in enumerate(lights["minimum_move_distribution"])]
    return overview, ntable, "\n".join(detail) + "\n"


def replace_block(document, start, end, value):
    source = document.read_text()
    left = source.index(start) + len(start)
    right = source.index(end, left)
    document.write_text(source[:left] + "\n" + value + "\n" + source[right:])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=pathlib.Path, default=ROOT / "build-release")
    parser.add_argument("--threads", type=int, default=6)
    parser.add_argument("--max-n", type=int, default=18)
    args = parser.parse_args()
    build = args.build.resolve()
    result_dir = ROOT / "results"
    result_dir.mkdir(exist_ok=True)
    print("N-Queens 1..", args.max_n, flush=True)
    queens = list(rows(build, args.max_n, args.threads))
    print("Tic-Tac-Toe", flush=True)
    ttt = run_json(build, "tictactoe")
    print("8-Puzzle", flush=True)
    puzzle = run_json(build, "eight_puzzle")
    print("Lights Out 5x5", flush=True)
    lights = run_json(build, "lights_out")
    if not (ttt["verified"] and puzzle["all_paths_replayed"] and lights["every_board_cross_checked"]):
        raise RuntimeError("an exhaustive verification failed")
    if sum(puzzle["histogram"]) != puzzle["reachable_states"]:
        raise RuntimeError("8-Puzzle histogram mismatch")
    if sum(lights["minimum_move_distribution"]) != lights["solvable_states"]:
        raise RuntimeError("Lights Out histogram mismatch")
    save(result_dir / "nqueens.json", {"rows": queens, "verified_through": args.max_n,
                                       "worker_threads": args.threads})
    save(result_dir / "tictactoe.json", ttt)
    save(result_dir / "eight_puzzle.json", puzzle)
    save(result_dir / "lights_out.json", lights)
    source_paths = [
        "src/nqueens/queens_recursive.cpp", "src/nqueens/queens_iterative.cpp",
        "src/nqueens/provenance/queens_recursive.cpp",
        "src/nqueens/provenance/queens_iterative.cpp",
        "src/tictactoe/main.cpp", "src/eight_puzzle/main.cpp",
        "src/lights_out/main.cpp",
    ]
    save(result_dir / "source_hashes.json", {
        path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
        for path in source_paths
    })
    env = environment(args.threads)
    env["measured_at_utc"] = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    save(result_dir / "environment.json", env)
    overview, ntable, tables = markdown(queens, ttt, puzzle, lights)
    (result_dir / "tables.md").write_text(tables)
    if args.max_n == 18:
        replace_block(ROOT / "README.md", "<!-- BEGIN VERIFIED RESULTS -->",
                      "<!-- END VERIFIED RESULTS -->", overview)
    benchmarks = "\n".join([
        "# Benchmarks", "", "Measured by `scripts/generate_results.py`; times are wall-clock seconds.",
        "Counts are exact; timings vary with hardware, compiler, and system load.", "",
        "## Environment", "",
        f"- CPU: {env['cpu']} ({env['logical_cpus']} logical CPUs; {args.threads} worker threads for N-Queens)",
        f"- OS: {env['os']}", f"- Compiler: {env['compiler']}", f"- Build: CMake Release, `-O3`, C++17",
        f"- CMake: {env['cmake']}", f"- Python: {env['python']}",
        f"- Measurement time: {env['measured_at_utc']}", "", "## N-Queens", "", ntable,
        "", "The two N=18 measurements were run sequentially. Each C++ binary measures",
        "its own compute time with `std::chrono::steady_clock`.", "",
        "## Other exhaustive runs", "", "| Project | Wall time (s) |",
        "|:--|--:|", f"| Tic-Tac-Toe | {ttt['runtime_seconds']:.6f} |",
        f"| 8-Puzzle | {puzzle['runtime_seconds']:.6f} |",
        f"| Lights Out 5×5 | {lights['runtime_seconds']:.6f} |", "",
        "The earlier N=18 provenance measurements are recorded separately in",
        "[`docs/provenance.md`](provenance.md).", ""])
    (ROOT / "docs" / "benchmarks.md").write_text(benchmarks)
    print("All four exhaustive analyses verified; result files regenerated.", flush=True)


if __name__ == "__main__":
    main()
